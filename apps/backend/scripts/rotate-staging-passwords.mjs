#!/usr/bin/env node
// [S2-05] Rotates the four seed staff accounts to fresh, distinct, random passwords and writes
// them to a GITIGNORED file — never to stdout, chat, a commit, or any log.
//
// Run this by hand, from your own machine, with the real service-role key:
//
//   cd apps/backend
//   SUPABASE_URL=https://<ref>.supabase.co SUPABASE_SERVICE_ROLE_KEY=<service role key> \
//     node scripts/rotate-staging-passwords.mjs
//
// The service-role key is in the Supabase dashboard → Project Settings → API, or wherever you keep
// the staging secrets already (this is the same key `STAGING_SUPABASE_SERVICE_ROLE_KEY` names in
// GitHub's environment `staging`). This script never asks for or stores it anywhere beyond the one
// process invocation.
//
// Output: apps/backend/.staff-credentials.local (gitignored — see apps/backend/.gitignore). Rerun
// any time you want to rotate again; the file is overwritten, not appended.
import { randomBytes } from "node:crypto";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { createClient } from "@supabase/supabase-js";

const STAFF = [
  { id: "10000000-0000-4000-8000-000000000001", email: "owner@shosho.test", role: "owner" },
  { id: "10000000-0000-4000-8000-000000000002", email: "operator@shosho.test", role: "operator" },
  { id: "10000000-0000-4000-8000-000000000003", email: "kitchen@shosho.test", role: "kitchen" },
  { id: "10000000-0000-4000-8000-000000000004", email: "driver@shosho.test", role: "driver" },
];

const url = process.env.SUPABASE_URL;
const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
if (!url || !serviceKey) {
  console.error(
    "rotate-staging-passwords: set SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY to the target " +
      "project's values — see the comment at the top of this file.",
  );
  process.exit(1);
}

// 160 bits, URL/form-safe alphabet — easy to paste into a login form, no ambiguous padding chars.
const freshPassword = () => randomBytes(20).toString("base64url");

const admin = createClient(url, serviceKey, { auth: { persistSession: false } });

const results = [];
let failed = false;
for (const person of STAFF) {
  const password = freshPassword();
  const { error } = await admin.auth.admin.updateUserById(person.id, { password });
  if (error) {
    failed = true;
    console.error(`rotate-staging-passwords: ${person.email}: ${error.message}`);
    continue;
  }
  results.push({ ...person, password });
}
if (failed || results.length !== STAFF.length) {
  console.error("rotate-staging-passwords: aborted — not all accounts were rotated, nothing written.");
  process.exit(1);
}

const here = dirname(fileURLToPath(import.meta.url));
const outPath = join(here, "..", ".staff-credentials.local");
const lines = [
  "# SHOSHO staging staff credentials — generated by scripts/rotate-staging-passwords.mjs",
  `# ${new Date().toISOString()} · target: ${url}`,
  "# This file is gitignored (apps/backend/.gitignore). Never commit it, paste it into chat, or",
  "# put it in a log entry. Re-run the script to rotate again; it overwrites this file.",
  "",
  ...results.map((r) => `${r.role}\t${r.email}\t${r.password}`),
  "",
];
writeFileSync(outPath, lines.join("\n"), { mode: 0o600 });

// Deliberately no password in this output — the file path is the deliverable.
console.log(`rotate-staging-passwords: rotated ${results.length} accounts on ${url}.`);
console.log(`  credentials written to ${outPath}`);
